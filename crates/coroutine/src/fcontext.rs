use core::arch::naked_asm;
use core::ffi::c_void;

#[cfg(not(any(target_arch = "x86_64", target_arch = "aarch64")))]
compile_error!("coroutine: no fcontext switch for this architecture (x86_64 and aarch64 only)");

/// What a jump hands the context it lands in: the context it left, and its data.
#[repr(C)]
pub(crate) struct Transfer {
    pub(crate) fctx: *mut c_void,
    pub(crate) data: *mut c_void,
}

/// Makes a context at the top of `stack` (its highest address) whose first jump calls
/// `entry`; `size` is unused, as in boost. If `entry` returns, the process exits with 0.
///
/// # Safety
/// `stack` is the top of a writable stack that outlives the context.
#[unsafe(naked)]
pub(crate) unsafe extern "C" fn make_fcontext(
    stack: *mut c_void,
    size: usize,
    entry: extern "C" fn(Transfer),
) -> *mut c_void {
    #[cfg(target_arch = "x86_64")]
    naked_asm!(
        // The frame: MXCSR, x87 CW, guard, R12-R15, RBX, RBP, RIP. RAX = top & -16, less
        // the frame: on context-function entry (RSP - 0x8) % 16 == 0.
        "movq  %rdi, %rax",
        "andq  $-16, %rax",
        "leaq  -0x48(%rax), %rax",
        // The context-function, restored into RBX.
        "movq  %rdx, 0x30(%rax)",
        "stmxcsr  (%rax)",
        "fnstcw   0x4(%rax)",
        // The trampoline is the first jump's return address; finish, restored into RBP,
        // becomes the context-function's.
        "leaq  2f(%rip), %rcx",
        "movq  %rcx, 0x40(%rax)",
        "leaq  3f(%rip), %rcx",
        "movq  %rcx, 0x38(%rax)",
        "ret",
        // trampoline: push the return address, fixing the alignment, and enter.
        "2:",
        "push %rbp",
        "jmp *%rbx",
        // finish: exit(0).
        "3:",
        "xorq  %rdi, %rdi",
        "call  {exit}",
        "hlt",
        exit = sym libc::_exit,
        options(att_syntax),
    );
    #[cfg(target_arch = "aarch64")]
    naked_asm!(
        // The frame: d8-d15, x19-x30, PC. x0 = top & ~0xF, less the frame.
        "and x0, x0, ~0xF",
        "sub  x0, x0, #0xb0",
        // The context-function is the PC, and finish its return address (LR).
        "str  x2, [x0, #0xa0]",
        "adr  x1, 2f",
        "str  x1, [x0, #0x98]",
        "ret  x30",
        // finish: exit(0).
        "2:",
        "mov  x0, #0",
        "bl  {exit}",
        exit = sym libc::_exit,
    );
}

/// Saves the running context, switches to `to`, and returns the [`Transfer`] of the
/// jump that switches back. A fresh context's function receives it as its argument.
///
/// # Safety
/// `to` came from [`make_fcontext`] or a [`Transfer`] and has not been resumed since.
#[unsafe(naked)]
pub(crate) unsafe extern "C" fn jump_fcontext(to: *mut c_void, data: *mut c_void) -> Transfer {
    #[cfg(target_arch = "x86_64")]
    naked_asm!(
        // Save MXCSR, the x87 CW and the callee-saved registers below the return address.
        "leaq  -0x40(%rsp), %rsp",
        "stmxcsr  (%rsp)",
        "fnstcw   0x4(%rsp)",
        "movq  %r12, 0x10(%rsp)",
        "movq  %r13, 0x18(%rsp)",
        "movq  %r14, 0x20(%rsp)",
        "movq  %r15, 0x28(%rsp)",
        "movq  %rbx, 0x30(%rsp)",
        "movq  %rbp, 0x38(%rsp)",
        // RAX = this context; RSP = `to`'s.
        "movq  %rsp, %rax",
        "movq  %rdi, %rsp",
        "movq  0x40(%rsp), %r8",
        "ldmxcsr  (%rsp)",
        "fldcw    0x4(%rsp)",
        "movq  0x10(%rsp), %r12",
        "movq  0x18(%rsp), %r13",
        "movq  0x20(%rsp), %r14",
        "movq  0x28(%rsp), %r15",
        "movq  0x30(%rsp), %rbx",
        "movq  0x38(%rsp), %rbp",
        "leaq  0x48(%rsp), %rsp",
        // The Transfer: returned in RAX:RDX, and RDI:RSI for a fresh context's function.
        "movq  %rsi, %rdx",
        "movq  %rax, %rdi",
        "jmp  *%r8",
        options(att_syntax),
    );
    #[cfg(target_arch = "aarch64")]
    naked_asm!(
        // Save d8-d15, x19-x30 and LR as the PC.
        "sub  sp, sp, #0xb0",
        "stp  d8,  d9,  [sp, #0x00]",
        "stp  d10, d11, [sp, #0x10]",
        "stp  d12, d13, [sp, #0x20]",
        "stp  d14, d15, [sp, #0x30]",
        "stp  x19, x20, [sp, #0x40]",
        "stp  x21, x22, [sp, #0x50]",
        "stp  x23, x24, [sp, #0x60]",
        "stp  x25, x26, [sp, #0x70]",
        "stp  x27, x28, [sp, #0x80]",
        "stp  x29, x30, [sp, #0x90]",
        "str  x30, [sp, #0xa0]",
        // x4 = this context; sp = `to`'s.
        "mov  x4, sp",
        "mov  sp, x0",
        "ldp  d8,  d9,  [sp, #0x00]",
        "ldp  d10, d11, [sp, #0x10]",
        "ldp  d12, d13, [sp, #0x20]",
        "ldp  d14, d15, [sp, #0x30]",
        "ldp  x19, x20, [sp, #0x40]",
        "ldp  x21, x22, [sp, #0x50]",
        "ldp  x23, x24, [sp, #0x60]",
        "ldp  x25, x26, [sp, #0x70]",
        "ldp  x27, x28, [sp, #0x80]",
        "ldp  x29, x30, [sp, #0x90]",
        // The Transfer in x0:x1 (`data` is already in x1), both returned and passed.
        "mov x0, x4",
        "ldr  x4, [sp, #0xa0]",
        "add  sp, sp, #0xb0",
        "ret x4",
    );
}
