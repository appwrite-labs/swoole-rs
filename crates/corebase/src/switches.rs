//! The build's switches, one bit each in `swr_cpp_switches`
//! (native/corebase/switches.cc, which `tools/headers.sh` generates from
//! [`SWITCHES`]). Some are crates/ext's build.rs defines, but the TLS library's
//! (`TLS1_3_VERSION`, `OPENSSL_IS_BORINGSSL`, `SW_SUPPORT_DTLS`) are header
//! macros, which only a C++ compile of those headers sees.
#[derive(Clone, Copy, PartialEq, Eq, Debug)]
#[repr(u8)]
pub enum Switch {
    ThreadContext,
    AsmContext,
    Debug,
    Trace,
    Epoll,
    Eventfd,
    Thread,
    Signalfd,
    Accept4,
    Affinity,
    Spinlock,
    Rwlock,
    Sockets,
    Dtls,
    Curl,
    Cares,
    Zlib,
    Brotli,
    Zstd,
    Timedlock,
    Barrier,
    Futex,
    Mysqlnd,
    Jemalloc,
    Tcmalloc,
    Pgsql,
    Odbc,
    Oracle,
    Sqlite,
    Firebird,
    IoUring,
    UringSocket,
    Stacktrace,
    Execinfo,
    Ssh2,
    Ftp,
    AiV4mapped,
    AiAll,
    AiIdn,
    TlsHostName,
    BoringSsl,
    IouringStatx,
    IouringFtruncate,
    IouringFutex,
    Tls1_1,
    Tls1_2,
    Tls1_3,
    Ssl3,
    ContextProtectStackPage,
    ContextDetectStackUsage,
    CoroTime,
}

