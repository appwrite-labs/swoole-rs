#[cfg(test)]
mod tests {
    #[test]
    fn the_header_numbers_every_op_alike() {
        let header = include_str!("../../../../native/process/swoole_rs_workers.h");
        for (name, value) in super::NUMBERED {
            let define = format!("#define SWR_WORKERS_{name} {value}\n");
            assert!(header.contains(&define), "{define}");
        }
        assert_eq!(
            header.matches("#define SWR_WORKERS_").count(),
            super::NUMBERED.len()
        );
    }
}
